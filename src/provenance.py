"""Run manifest: records WHAT data a run used (source, range, counts, synthetic or not) and
how it was produced (package versions). Every stage appends to it; the dashboard displays it."""
import json
import os
import platform
import shutil
import sys
from datetime import datetime, timezone
from importlib import metadata

import config

PKGS = ["duckdb", "pandas", "numpy", "pyarrow", "scikit-learn", "scipy", "matplotlib",
        "seaborn", "folium", "streamlit", "requests", "joblib"]


def _now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _versions():
    out = {}
    for p in PKGS:
        try:
            out[p] = metadata.version(p)
        except metadata.PackageNotFoundError:
            out[p] = None
    return out


def _write(m, path=None):
    path = path or config.MANIFEST
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(m, indent=2, default=str))
    os.replace(tmp, path)


def load(path=None):
    path = path or config.MANIFEST
    return json.loads(path.read_text()) if path.exists() else None


def init_run():
    """Create the manifest on first use; refuse to continue if it belongs to a different run/mode."""
    m = load()
    if m is None:
        m = {"mode": config.MODE, "is_synthetic": config.IS_SYNTHETIC,
             "data_source": ("SYNTHETIC - generated by src/make_sample_data.py (NOT Citi Bike data)"
                             if config.IS_SYNTHETIC else "Citi Bike official trip data, https://s3.amazonaws.com/tripdata/"),
             "start_month": config.START_MONTH, "end_month": config.END_MONTH, "run_tag": config.RUN_TAG,
             "created_at": _now(), "environment": {"python": sys.version.split()[0],
                                                   "platform": platform.platform(), "packages": _versions()},
             "stages": {}}
        _write(m)
        return m
    mismatch = [k for k, v in (("mode", config.MODE), ("start_month", config.START_MONTH),
                               ("end_month", config.END_MONTH)) if m.get(k) != v]
    if mismatch:
        raise SystemExit(f"Manifest {config.MANIFEST} belongs to a different run ({mismatch}). Refusing to mix runs.")
    return m


def update(stage, info):
    m = init_run()
    m["stages"][stage] = {**info, "completed_at": _now()}
    _write(m)
    return m


def completed_stages():
    m = load()
    return list(m["stages"]) if m else []


def require_stage(stage):
    m = init_run()
    if stage not in m["stages"]:
        raise SystemExit(f"Stage '{stage}' has not completed for run {config.RUN_TAG} ({config.MODE}). "
                         f"Run the earlier phase first.")
    return m


def publish_to_reports():
    """Copy manifest + exclusion report next to the figures so the dashboard/notebooks can show provenance."""
    if config.MANIFEST.exists():
        shutil.copy(config.MANIFEST, config.REP_DATA / "run_manifest.json")
    if config.EXCLUSION_REPORT.exists():
        shutil.copy(config.EXCLUSION_REPORT, config.REP_DATA / "exclusion_report.csv")
    note = ("SYNTHETIC DATA - test artifacts only, not Citi Bike findings.\n" if config.IS_SYNTHETIC
            else "Real Citi Bike data - see run_manifest.json for coverage.\n")
    (config.FIG / "PROVENANCE.txt").write_text(note + f"run: {config.MODE}/{config.RUN_TAG}\n")


def banner():
    return (f"[{config.MODE.upper()}] {config.START_MONTH}..{config.END_MONTH}"
            + ("  *** SYNTHETIC DATA - NOT REAL CITI BIKE FINDINGS ***" if config.IS_SYNTHETIC else ""))


def stamp_figure(fig=None):
    """Watermark figures produced from synthetic data so they cannot be mistaken for real results."""
    if not config.IS_SYNTHETIC:
        return
    import matplotlib.pyplot as plt
    fig = fig or plt.gcf()
    fig.text(0.5, 0.5, "SYNTHETIC DATA", fontsize=44, color="red", alpha=0.13,
             ha="center", va="center", rotation=25, zorder=100)
