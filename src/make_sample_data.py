"""OFFLINE TEST DATA - synthetic Citi Bike CSVs (new schema) + fake weather + fake capacities.
Lets you test the full pipeline (cleaning -> features -> EDA -> modeling) with no internet:
    python run_all.py sample
Contains deliberately dirty rows (duplicates, negative/huge durations, bad coords, depot trips).
DO NOT use results for conclusions - the data is fake. Delete data/ before the real run.
"""
import numpy as np
import pandas as pd
import config
import provenance
from config import RAW, WEATHER_PQ, STATION_INFO, START_MONTH, END_MONTH

if not config.IS_SYNTHETIC:
    raise SystemExit("Refusing to run: make_sample_data.py only works with DATA_MODE=sample "
                     "(use `python run_all.py sample`). Real data must never be mixed with synthetic data.")
provenance.init_run()
config.SYNTHETIC_MARKER.write_text("Every file in this folder was generated by src/make_sample_data.py. NOT Citi Bike data.\n")
_total_rows = 0

rng = np.random.default_rng(42)
N_PER_MONTH = 60_000
months = pd.period_range(START_MONTH, END_MONTH, freq="M")

# ---------- stations ----------
n_st = 250
st = pd.DataFrame({
    "id": [f"{6000 + i}.{rng.integers(1, 99):02d}" for i in range(n_st)],
    "name": [f"{rng.integers(1, 120)} St & {rng.integers(1, 12)} Ave #{i}" for i in range(n_st)],
    "lat": rng.uniform(40.70, 40.79, n_st), "lng": rng.uniform(-74.01, -73.95, n_st)})
w_st = rng.pareto(1.5, n_st) + 1
w_st /= w_st.sum()
pd.DataFrame({"station_id": st.id, "name": st.name, "lat": st.lat, "lon": st.lng,
              "capacity": rng.integers(20, 70, n_st)}).to_parquet(STATION_INFO, index=False)

# ---------- fake weather ----------
hrs = pd.date_range(months[0].start_time, months[-1].end_time.floor("h"), freq="h")
doy = hrs.dayofyear.values
temp = 12 - 14 * np.cos(2 * np.pi * (doy - 15) / 365) + 4 * np.sin(2 * np.pi * (hrs.hour.values - 9) / 24)
wet_day = pd.Series(rng.random(len(hrs.normalize().unique())) < 0.25, index=hrs.normalize().unique())
wet = wet_day.reindex(hrs.normalize()).values
precip = np.where(wet & (rng.random(len(hrs)) < 0.5), rng.exponential(1.5, len(hrs)), 0.0)
wx = pd.DataFrame({"hour_ts": hrs, "temp_c": temp + rng.normal(0, 1.5, len(hrs)),
                   "humidity": rng.uniform(35, 95, len(hrs)), "precip_mm": precip,
                   "snow_cm": np.where((temp < 0) & (precip > 0), precip * 0.8, 0.0),
                   "wind_kmh": rng.gamma(4, 3, len(hrs)), "weather_code": 0})
wx.to_parquet(WEATHER_PQ, index=False)
wx_i = wx.set_index("hour_ts")


def hav(la1, lo1, la2, lo2):
    p = np.pi / 180
    a = np.sin((la2 - la1) * p / 2) ** 2 + np.cos(la1 * p) * np.cos(la2 * p) * np.sin((lo2 - lo1) * p / 2) ** 2
    return 12742 * np.arcsin(np.sqrt(a))


for m in months:
    n = int(N_PER_MONTH * 1.6)
    days = pd.date_range(m.start_time, m.end_time.normalize(), freq="D")
    d = rng.choice(days, n)
    is_wkend = pd.DatetimeIndex(d).dayofweek >= 5
    hour = np.where(is_wkend, rng.normal(14, 4, n), np.where(rng.random(n) < .55,
                    rng.choice([8, 17.5], n) + rng.normal(0, 1.2, n), rng.normal(13, 4.5, n)))
    hour = np.clip(hour, 0, 23.99)
    start = pd.to_datetime(d) + pd.to_timedelta(hour * 3600, unit="s")
    w = wx_i.reindex(start.floor("h"))
    keep_p = np.clip(0.35 + 0.03 * w.temp_c.fillna(10).values, 0.1, 1) * np.where(w.precip_mm.fillna(0).values > 0.2, 0.35, 1)
    keep = rng.random(n) < keep_p
    start = start[keep][:N_PER_MONTH]
    n = len(start)
    a = rng.choice(n_st, n, p=w_st)
    b = rng.choice(n_st, n, p=w_st)
    member = rng.random(n) < 0.78
    ebike = rng.random(n) < 0.35
    dist = hav(st.lat.values[a], st.lng.values[a], st.lat.values[b], st.lng.values[b])
    speed = np.where(ebike, 17, 12) * np.where(member, 1.0, 0.7)
    dur = dist / speed * 3600 * rng.lognormal(0.1, 0.35, n) + rng.exponential(150, n) + np.where(member, 0, 400)
    dur = np.maximum(dur, 75)
    df = pd.DataFrame({
        "ride_id": [f"{x:016X}" for x in rng.integers(0, 2**62, n)],
        "rideable_type": np.where(ebike, "electric_bike", "classic_bike"),
        "started_at": start, "ended_at": start + pd.to_timedelta(dur, unit="s"),
        "start_station_name": st.name.values[a], "start_station_id": st.id.values[a],
        "end_station_name": st.name.values[b], "end_station_id": st.id.values[b],
        "start_lat": st.lat.values[a] + rng.normal(0, 3e-4, n), "start_lng": st.lng.values[a] + rng.normal(0, 3e-4, n),
        "end_lat": st.lat.values[b] + rng.normal(0, 3e-4, n), "end_lng": st.lng.values[b] + rng.normal(0, 3e-4, n),
        "member_casual": np.where(member, "member", "casual")})
    # ---- dirt ----
    i = rng.choice(n, int(n * .01), replace=False); df.loc[i, "ended_at"] = df.loc[i, "started_at"] - pd.Timedelta(minutes=5)
    i = rng.choice(n, int(n * .01), replace=False); df.loc[i, "ended_at"] = df.loc[i, "started_at"] + pd.Timedelta(hours=30)
    i = rng.choice(n, int(n * .01), replace=False); df.loc[i, ["end_lat", "end_lng"]] = np.nan
    i = rng.choice(n, int(n * .005), replace=False); df.loc[i, "start_lat"] = 0.0
    i = rng.choice(n, int(n * .005), replace=False); df.loc[i, "start_station_name"] = "  " + df.loc[i, "start_station_name"] + "  "
    i = rng.choice(n, int(n * .003), replace=False); df.loc[i, "end_station_name"] = "Depot Warehouse"
    df = pd.concat([df, df.sample(int(n * .01), random_state=1)])           # duplicate ride_ids
    for c in ("started_at", "ended_at"):
        df[c] = pd.to_datetime(df[c]).dt.strftime("%Y-%m-%d %H:%M:%S.%f").str[:-3]
    out = RAW / f"{m.strftime('%Y%m')}-citibike-tripdata_1.csv"
    df.to_csv(out, index=False)
    _total_rows += len(df)
    print("wrote", out.name, f"{len(df):,} rows")
print("Fake weather ->", WEATHER_PQ, "| fake capacity ->", STATION_INFO)
provenance.update("source", {"kind": "SYNTHETIC", "generator": "src/make_sample_data.py", "csv_rows_written": _total_rows,
                            "months": [str(m) for m in months], "seed": 42})
